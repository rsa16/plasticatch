/** Whether `code` is one of the accepted state codes. */
export function isUsStateCode(code: string | null | undefined): code is string {
  return typeof code === 'string' && US_STATES.some((state) => state.code === code);
}

/** The player-facing name for a stored code, or `null` when it is missing or unknown. */
export function usStateName(code: string | null | undefined): string | null {
  return US_STATES.find((state) => state.code === code)?.name ?? null;
}
